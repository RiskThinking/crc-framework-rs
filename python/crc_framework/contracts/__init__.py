"""Versioned impact contract artifact: JSON Schemas, catalogs and conformance fixtures.

The artifact is generated by ``tools/impact_contracts/generate.py`` from an
independent reference implementation. Consumers pin
``impact_contract_manifest_sha256()`` and call ``verify_impact_contracts()``
before relying on the files.
"""

from __future__ import annotations

import hashlib
import json
from importlib import resources
from typing import Any, Dict, List

IMPACT_CONTRACT_ARTIFACT = "crc-impact-contracts"
IMPACT_CONTRACT_VERSION = "1.0.0"

_PACKAGE = "crc_framework.contracts"
_ROOT = "impact"


def _read_bytes(relative_path: str) -> bytes:
    if relative_path.startswith("/") or ".." in relative_path.split("/"):
        raise ValueError(f"invalid contract path {relative_path!r}")
    node = resources.files(_PACKAGE).joinpath(_ROOT)
    for part in relative_path.split("/"):
        node = node.joinpath(part)
    return node.read_bytes()


def read_impact_contract_file(relative_path: str) -> bytes:
    """Return the exact bytes of an artifact file, for example ``schemas/...``."""
    return _read_bytes(relative_path)


def load_impact_contract_file(relative_path: str) -> Any:
    return json.loads(_read_bytes(relative_path).decode("utf-8"))


def impact_contract_manifest() -> Dict[str, Any]:
    manifest: Dict[str, Any] = load_impact_contract_file("manifest.json")
    return manifest


def impact_contract_manifest_sha256() -> str:
    """Bare SHA-256 of ``manifest.json``; pinning it pins every listed file."""
    return hashlib.sha256(_read_bytes("manifest.json")).hexdigest()


def load_impact_schema(contract: str) -> Dict[str, Any]:
    """Load the JSON Schema for a contract such as ``impact_definition``."""
    entry = impact_contract_manifest()["contracts"][contract]
    schema: Dict[str, Any] = load_impact_contract_file(entry["schema"])
    return schema


def load_impact_fixtures(contract: str) -> Dict[str, Any]:
    """Load accepted and rejected conformance cases for a contract."""
    entry = impact_contract_manifest()["contracts"][contract]
    fixtures: Dict[str, Any] = load_impact_contract_file(entry["fixtures"])
    return fixtures


def impact_contract_names() -> List[str]:
    return sorted(impact_contract_manifest()["contracts"])


def verify_impact_contracts() -> None:
    """Check the artifact identity and every file digest listed in the manifest."""
    manifest = impact_contract_manifest()
    if manifest.get("artifact") != IMPACT_CONTRACT_ARTIFACT:
        raise ValueError(f"unexpected contract artifact {manifest.get('artifact')!r}")
    if manifest.get("artifact_version") != IMPACT_CONTRACT_VERSION:
        raise ValueError(f"unexpected contract version {manifest.get('artifact_version')!r}")
    for entry in manifest["files"]:
        content = _read_bytes(entry["path"])
        if len(content) != entry["bytes"] or hashlib.sha256(content).hexdigest() != entry["sha256"]:
            raise ValueError(f"impact contract file {entry['path']} does not match the manifest")


__all__ = [
    "IMPACT_CONTRACT_ARTIFACT",
    "IMPACT_CONTRACT_VERSION",
    "impact_contract_manifest",
    "impact_contract_manifest_sha256",
    "impact_contract_names",
    "load_impact_contract_file",
    "load_impact_fixtures",
    "load_impact_schema",
    "read_impact_contract_file",
    "verify_impact_contracts",
]
